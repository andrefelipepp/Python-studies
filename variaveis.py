# As variáveis são como "caixas" onde você armazena valores 🗃️. Elas permitem que você manipule dados de forma dinâmica durante 
# a execução do seu programa.

idade = 23 # A variável 'idade' agora contém um inteiro
nome = "Felipe" # A variável 'nome' agora contém uma string
peso = 70.00 # # A variável 'peso' agora contém uma float

### Regras para nomear variáveis

# Devem começar com uma letra ou `_` (underline).
# Não podem começar com um número.
# Não podem conter espaços ou caracteres especiais como `@`, `#`, `!`.
# São **case-sensitive** (`idade` e `Idade` são variáveis diferentes).

# 💡 Imagine as variáveis como "etiquetas" que você coloca em caixas 📦. A etiqueta "idade" pode estar associada ao número `23`,
# e a etiqueta "nome" ao texto `"Felipe"`.
